#!/usr/bin/env node
// Bundle automation/run.mjs (+ js/core, js/analytics, js/ai, web-push) into one
// self-contained ESM file for Node 20+: dist/forge-automation.mjs, plus
// dist/automation-version.json { version, builtAt, sha256, bytes }.
//
//   node tools/build-automation.mjs                 strict: every js/analytics|js/ai module must exist
//   node tools/build-automation.mjs --allow-missing stub missing analytics/AI modules (dev only;
//                                                   the features that need them report "not available")
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { builtinModules } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const allowMissing = process.argv.includes('--allow-missing') || process.env.FORGE_ALLOW_MISSING === '1';
const outDir = join(root, 'dist');
const outFile = join(outDir, 'forge-automation.mjs');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const version = String(pkg.version || '0.0.0');
const builtAt = new Date().toISOString();
const rel = (p) => relative(root, p).split('\\').join('/');

// Analytics and AI modules are developed alongside automation; resolve them explicitly so a
// missing one is a clear build error (or, with --allow-missing, an explicit stub).
const missing = [];
const optionalModules = {
  name: 'forge-optional-modules',
  setup(b) {
    b.onResolve({ filter: /(^|\/)js\/(analytics|ai)\/[\w.-]+\.js$/ }, (args) => {
      const abs = resolve(args.resolveDir, args.path);
      if (existsSync(abs)) return null;
      missing.push(rel(abs));
      if (!allowMissing) return { errors: [{ text: `missing module ${rel(abs)} (build with --allow-missing to stub it)` }] };
      return { path: abs, namespace: 'forge-missing' };
    });
    b.onLoad({ filter: /.*/, namespace: 'forge-missing' }, (args) => ({
      contents: `export const __forgeMissing = ${JSON.stringify(rel(args.path))};\n`,
      loader: 'js',
    }));
  },
};

// web-push lazily requires https-proxy-agent (→ agent-base → debug → optional supports-color)
// only when a proxy option is passed. Automation never uses one, so keep it out of the bundle.
const noProxyAgent = {
  name: 'forge-no-proxy-agent',
  setup(b) {
    b.onResolve({ filter: /^https-proxy-agent$/ }, () => ({ path: 'https-proxy-agent', namespace: 'forge-stub' }));
    b.onLoad({ filter: /.*/, namespace: 'forge-stub' }, () => ({
      contents: "module.exports = { HttpsProxyAgent: class { constructor() { throw new Error('proxy support is not bundled'); } } };\n",
      loader: 'js',
    }));
  },
};

const banner = [
  `// FORGE automation v${version}, built ${builtAt}`,
  '// Generated by tools/build-automation.mjs from automation/run.mjs; do not edit.',
  '// Runs in the vault checkout root: node automation/forge-automation.mjs',
  "import { createRequire as __forgeCreateRequire } from 'node:module';",
  'const require = __forgeCreateRequire(import.meta.url);',
].join('\n');

await mkdir(outDir, { recursive: true });
const result = await build({
  absWorkingDir: root,
  entryPoints: [join(root, 'automation/run.mjs')],
  outfile: outFile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: ['node20'],
  charset: 'utf8',
  legalComments: 'eof',
  banner: { js: banner },
  define: {
    __FORGE_AUTOMATION_VERSION__: JSON.stringify(version),
    __FORGE_AUTOMATION_BUILT_AT__: JSON.stringify(builtAt),
  },
  plugins: [optionalModules, noProxyAgent],
  metafile: true,
  logLevel: 'warning',
});

// Self-containment check: the only runtime imports left must be Node built-ins.
const builtins = new Set(builtinModules.flatMap((m) => [m, `node:${m}`]));
const output = result.metafile.outputs[rel(outFile)] || Object.values(result.metafile.outputs)[0];
const external = (output.imports || []).map((i) => i.path).filter((p) => !builtins.has(p) && !p.startsWith('node:'));
if (external.length) {
  console.error(`build-automation: bundle still imports non-built-in modules: ${[...new Set(external)].join(', ')}`);
  process.exit(1);
}

const bytes = await readFile(outFile);
const sha256 = createHash('sha256').update(bytes).digest('hex');
const info = { version, builtAt, sha256, bytes: bytes.length };
if (missing.length) info.missing = [...new Set(missing)].sort();
await writeFile(join(outDir, 'automation-version.json'), JSON.stringify(info, null, 2) + '\n');

const inputs = Object.keys(result.metafile.inputs);
console.log(`build-automation: ${rel(outFile)} ${(bytes.length / 1024).toFixed(1)} KiB from ${inputs.length} modules, sha256 ${sha256.slice(0, 16)}…`);
if (info.missing) console.warn(`build-automation: WARNING stubbed missing modules: ${info.missing.join(', ')}`);
